'use client'

/**
 * زرّ «أضف إلى تقويمي» 🗓 — يولّد ملف `.ics` للقاء الواحد.
 *
 * النموذج يبني الملف في المتصفح بـ`URL.createObjectURL` ثم ينقر وسماً غير
 * مُلحَق بالمستند ويُبطل الرابط في الدورة نفسها. يعمل في Chrome، ويُجهض
 * التنزيل في Firefox، و**لا يحترم Safari على iOS سمة `download` لرابط blob**
 * فلا يحدث شيء إطلاقاً.
 *
 * وهذا الزرّ هو البديل الوحيد للتنبيهات الآلية بحسب حصيلة القرارات (§٦)،
 * فسقوطه على آيفون يُسقط الميزة عند شريحة كبيرة من الجمهور.
 *
 * فالتوليد انتقل إلى معالج مسار على الخادم يُرسل ترويسة
 * `Content-Disposition: attachment`، ويعمل على كل متصفح. والعنصر بقي
 * `<button className="ics">` كما في النموذج بالضبط — أصناف الورقة تفترض
 * عنصراً كتليّاً بعرض وارتفاع ٣٤ بكسل، ولا تنطبق على `<a>` سطريّ.
 * فالشكل مطابق، والسلوك أصحّ.
 */
export function IcsButton({ id }: { id: string }) {
  return (
    <button
      className="ics"
      title="أضف إلى تقويمي"
      aria-label="أضف هذا اللقاء إلى تقويمي"
      onClick={() => {
        // ⚠️ لا تُعيَّن window.location.href هنا: ذاك تنقّلٌ كامل يستبدل المستند،
        // فلو تعثّرت قاعدة البيانات لحظتها وعاد المسار برمز ٥٠٣ ونصّ عادي،
        // لوجد الزائر نفسه في صفحة بيضاء فيها سطر واحد بلا رابط عودة —
        // وقد فقد الجدول والبطل والتقويم. والقسم ٧ يمنع ذلك صراحةً.
        // رابط تنزيل من الأصل نفسه لا يستبدل المستند مهما كانت الاستجابة.
        const a = document.createElement('a')
        a.href = `/api/ics/${id}`
        a.download = ''
        a.rel = 'noopener'
        document.body.appendChild(a)
        a.click()
        a.remove()
      }}
    >
      🗓
    </button>
  )
}
