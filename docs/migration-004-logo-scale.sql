-- =============================================================
-- هجرة ٠٠٤ — ضبط حجم شعار الجمعية (logo_scale)
-- منصة اللقاءات العلمية · جمعية سنن
--
-- إضافة بحتة: عمود واحد بقيمة افتراضية وقيد مدى، بلا مساس بأي عمود أو
-- صفّ قائم. تعمل المنصة الحالية بلا أي تعديل كود فور تشغيلها —
-- logo_scale تُقرأ ١٠٠ لكل الاستعلامات القائمة التي لا تعرفها بعد.
-- =============================================================

-- فحص قبلي — شغّله وحده أولاً
select column_name from information_schema.columns
 where table_name = 'settings' and column_name = 'logo_scale';
-- المتوقَّع: صفّ واحد فارغ (لا نتائج) — العمود غير موجود بعد.
-- لو أعاد صفاً، فالهجرة نُفِّذت سابقاً؛ توقّف ولا تكمل.

begin;

alter table settings add column logo_scale smallint not null default 100;

alter table settings add constraint settings_logo_scale_range
  check (logo_scale between 60 and 140);

commit;


-- =============================================================
-- تحقّق بعد التنفيذ — شغّله وأرسل لي المخرجات
-- =============================================================

-- ١) القيمة الحالية ضمن المدى (يجب أن تعيد صفّاً واحداً: ١٠٠)
select logo_scale from settings;

-- ٢) القيد يرفض ما هو خارج المدى (يجب أن يفشل برسالة تذكر
--    settings_logo_scale_range — هذا الفشل هو النجاح المتوقَّع)
update settings set logo_scale = 200 where id = true;
