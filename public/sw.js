//
// القاعدة ٦.٢ في تعليمة البناء تمنع تخزين أي صفحة تقرأ v_lectures، لأن
// الحالة (قادم/جارٍ/منتهٍ) والعدّاد يعتمدان على now(). تخزين بيانات هنا
// كان سيُري الزائر أو المشرف حالة قديمة مجمَّدة أثناء العمل بلا اتصال —
// وهو أخطر من عدم التثبيت أصلاً. فهذا العامل موجود لغرض واحد: تحقيق
// شرط "قابلية التثبيت" في أندرويد/كروم، ولا يعترض طلباً واحداً.

self.addEventListener('install', (event) => {
  self.skipWaiting()
})

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim())
})

